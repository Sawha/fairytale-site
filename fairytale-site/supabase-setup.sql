-- Таблиця казок
CREATE TABLE stories (
  id BIGSERIAL PRIMARY KEY,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  moral TEXT NOT NULL,
  cover_emoji TEXT NOT NULL DEFAULT '📖',
  published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Індекс для швидкого сортування за датою
CREATE INDEX idx_stories_published_at ON stories (published_at DESC);

-- Row Level Security (RLS) — вмикаємо безпеку
ALTER TABLE stories ENABLE ROW LEVEL SECURITY;

-- Публічне читання (всі можуть читати опубліковані казки)
CREATE POLICY "Публічне читання казок" ON stories
  FOR SELECT
  USING (published_at <= NOW());

-- Тільки service role може вставляти (для GitHub Actions)
CREATE POLICY "Тільки сервіс може додавати" ON stories
  FOR INSERT
  WITH CHECK (auth.role() = 'service_role');

